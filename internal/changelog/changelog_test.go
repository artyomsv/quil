// Invariants that must hold forever. Not bound to the file's contents, which
// change on every release.
func TestEmbeddedHighlights_IsWellFormedAndNewestFirst(t *testing.T) {
	rels := All()
	for i, r := range rels {
		if _, _, _, err := version.Parsed(r.Version); err != nil {
			t.Errorf("release %d has unparseable version %q", i, r.Version)
		}
		if i == 0 {
			continue
		}
		cmp, err := version.Compare(rels[i-1].Version, r.Version)
		if err != nil {
			t.Fatalf("comparing %q and %q: %v", rels[i-1].Version, r.Version, err)
		}
		if cmp <= 0 {
			t.Errorf("records are not newest-first: %q precedes %q", rels[i-1].Version, r.Version)
		}
	}
}

