const sample = `# generated by scripts/promote-changelog.sh — do not edit
V 1.52.0 2026-03-03
A Worktree panes open from the tab menu
F Paste no longer drops the first character
V 1.51.0 2026-02-02
C F1 → Shortcuts is derived from your keymap
D The json_transform action is going away
R The legacy pane migration prompt is gone
S Tokens are no longer written to the MCP log
V 1.50.0 2026-01-01
V 1.49.0 2025-12-01
A An older feature
`

func TestParseHighlights_ReadsReleasesNewestFirst(t *testing.T) {
	rels := parseHighlights([]byte(sample))
	if len(rels) != 4 {
		t.Fatalf("got %d releases, want 4", len(rels))
	}
	if rels[0].Version != "1.52.0" || rels[0].Date != "2026-03-03" {
		t.Errorf("first release = %q %q, want 1.52.0 2026-03-03", rels[0].Version, rels[0].Date)
	}
	if rels[3].Version != "1.49.0" {
		t.Errorf("last release = %q, want 1.49.0", rels[3].Version)
	}
	if len(rels[0].Entries) != 2 {
		t.Fatalf("1.52.0 has %d entries, want 2", len(rels[0].Entries))
	}
	if rels[0].Entries[0].Kind != KindAdded ||
		rels[0].Entries[0].Text != "Worktree panes open from the tab menu" {
		t.Errorf("entry 0 = %v %q", rels[0].Entries[0].Kind, rels[0].Entries[0].Text)
	}
	if len(rels[2].Entries) != 0 {
		t.Errorf("1.50.0 has %d entries, want 0", len(rels[2].Entries))
	}
}

func TestParseHighlights_AllKindLetters(t *testing.T) {
	rels := parseHighlights([]byte(sample))
	want := []Kind{KindChanged, KindDeprecated, KindRemoved, KindSecurity}
	got := rels[1].Entries
	if len(got) != len(want) {
		t.Fatalf("1.51.0 has %d entries, want %d", len(got), len(want))
	}
	for i := range want {
		if got[i].Kind != want[i] {
			t.Errorf("entry %d kind = %v, want %v", i, got[i].Kind, want[i])
		}
	}
}

func TestParseHighlights_SkipsMalformedLinesWithoutFailing(t *testing.T) {
	in := `# comment
Z unknown letter
V
V 1.1.0
A orphan before any version
V 1.2.0 2026-01-01
A kept
`
	rels := parseHighlights([]byte(in))
	if len(rels) != 1 {
		t.Fatalf("got %d releases, want 1 (only the well-formed V line)", len(rels))
	}
	if rels[0].Version != "1.2.0" || len(rels[0].Entries) != 1 || rels[0].Entries[0].Text != "kept" {
		t.Errorf("got %+v, want 1.2.0 with one entry %q", rels[0], "kept")
	}
}

